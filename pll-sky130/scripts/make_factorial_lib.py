#!/usr/bin/env python3
"""Build a textbook 3x3 factorial corner library (NMOS in {s,t,f} x PMOS in {s,t,f}) from the sky130B ngspice
(legacy per-corner model) files the project simulates with: libs.tech/ngspice/sky130.lib.spice.

Why: in the PDK's own corner set, the skew corners sf / fs are not "between" ss and ff for either device
(measured: NMOS Vth shifts about +/-25 mV in ss/ff but ~36 mV in sf/fs; see results/corner_audit/).  The textbook set
takes the NMOS 1.8 V model from the ss / tt / ff corner and the PMOS model independently from ss / tt / ff, so every
device stays inside its own [slow, fast] envelope.  Section "n<N>p<P>": NMOS state N, PMOS state P.
n == p uses the PDK's own corners/{ss,tt,ff}.spice unchanged (exact reproduction); mixed states swap only the two
sky130_fd_pr__nfet_01v8 / pfet_01v8 model includes of corners/tt.spice.

Output: env/sky130_factorial.lib.spice (+ env/factorial/corner_n?p?.spice).   Usage: make_factorial_lib.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NG = Path("/home/pocopepe/pdk/volare/sky130/versions/c6d73a35f524070e85faff4a6a9eef49553ebc2b/sky130B/libs.tech/ngspice")
STATE = {"s": "ss", "t": "tt", "f": "ff"}


def absolute(text):
    """Rewrite relative .include paths (relative to libs.tech/ngspice/corners) to absolute ones."""
    def fix(m):
        p = (NG / "corners" / m.group(1)).resolve()
        return f'.include "{p}"'
    return re.sub(r'^\.include "([^"]+)"', fix, text, flags=re.M)


def main():
    (ROOT / "env/factorial").mkdir(parents=True, exist_ok=True)
    tt = (NG / "corners/tt.spice").read_text()
    out = ["* sky130B textbook factorial corners n<N>p<P>, N,P in {s,t,f}. Generated by scripts/make_factorial_lib.py", ""]
    for n in "stf":
        for p in "stf":
            if n == p:
                cf, spec = NG / f"corners/{STATE[n]}.spice", NG / f"corners/{STATE[n]}/specialized_cells.spice"
            else:
                body = tt.replace("sky130_fd_pr__nfet_01v8__tt.pm3", f"sky130_fd_pr__nfet_01v8__{STATE[n]}.pm3")
                body = body.replace("sky130_fd_pr__pfet_01v8__tt.corner", f"sky130_fd_pr__pfet_01v8__{STATE[p]}.corner")
                assert body != tt
                cf = ROOT / f"env/factorial/corner_n{n}p{p}.spice"
                cf.write_text(absolute(body))
                spec = NG / "corners/tt/specialized_cells.spice"
            if n == p:
                tmp = ROOT / f"env/factorial/corner_n{n}p{p}.spice"
                tmp.write_text(absolute(cf.read_text()))
                cf = tmp
            out += [f".lib n{n}p{p}", ".param mc_mm_switch=0", ".param mc_pr_switch=0",
                    f'.include "{cf}"',
                    f'.include "{NG}/r+c/res_typical__cap_typical.spice"',
                    f'.include "{NG}/r+c/res_typical__cap_typical__lin.spice"',
                    f'.include "{spec}"', f".endl n{n}p{p}", ""]
    (ROOT / "env/sky130_factorial.lib.spice").write_text("\n".join(out))
    print("wrote env/sky130_factorial.lib.spice with 9 sections")


if __name__ == "__main__":
    main()
