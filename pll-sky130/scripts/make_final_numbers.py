#!/usr/bin/env python3
"""Write results/final_numbers.md: every headline number of the final review, generated from the raw result files."""
import csv, json
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
O = ["nsps", "nspt", "nspf", "ntps", "ntpt", "ntpf", "nfps", "nfpt", "nfpf", "pdk_sf", "pdk_fs"]
comp = {r["corner"]: r for r in json.load(open(ROOT / "results/comp/factorial/factorial_comp_all.json"))}
camp = {r["case"]: r for r in csv.DictReader(open(ROOT / "results/loop/campaign/summary.csv"))}
dev = list(csv.DictReader(open(ROOT / "results/corner_audit/device_corners.csv")))
fa = json.load(open(ROOT / "results/corner_audit/factorial_summary.json"))
L = ["# Final numbers (generated by scripts/make_final_numbers.py from results/*; do not edit by hand)", ""]
L += ["## Compensation on 11 corners (nominal, ideal behavioural source; least-squares fit on measured f(T,V); verified by simulation)", "",
      "| corner | f(0.9 V, 27 C) MHz | baseline span % | 1st-order span % | 2nd-order span % | 2nd max dev % | held-out max dev % | C = base/2nd | k1 (V/C) | k2 (V/C^2) | meets +/-0.3 % |", "|---|---|---|---|---|---|---|---|---|---|---|"]
for c in O:
    r = comp[c]
    L.append(f"| {c} | {r['f27_MHz']:.1f} | {r['baseline']['span_pct']:.2f} | {r['order1']['span_pct']:.2f} | {r['order2']['span_pct']:.2f} | {r['order2']['maxdev_pct']:.3f} | {r['holdout']['maxdev_pct']:.3f} | {r['compensation_ratio_C']:.1f} | {r['order2']['k1']:.4e} | {r['order2']['k2']:.4e} | {'yes' if r['meets_0p3pct'] else 'NO'} |")
L += ["", "## Closed loop (R2 = 3.6 kOhm, C1 68 pF, C2 6.8 pF, Icp 20 uA, N = 8; spec lock < 2000 ns; lock = V_ctrl within +/-2 % of final)", "",
      "| case | lock ns | f_VCO MHz | f error % | V_ctrl lock V | ripple mV | peak V | settled |", "|---|---|---|---|---|---|---|---|"]
for k, r in camp.items():
    L.append(f"| {k} | {r['lock_ns']} | {r['f_vco_MHz']} | {r['f_err_pct']} | {r['vctrl_final_V']} | {r['ripple_mV']} | {r['peak_V']} | {r['settled']} |")
L += ["", "## Single-device audit (ngspice lib, W/L 2/0.5 um)", "", "| corner | T C | NMOS Id 0.9 V uA | PMOS Id 0.9 V uA | NMOS Id 1.8 V uA | PMOS Id 1.8 V uA | NMOS Vth V | PMOS |Vth| V |", "|---|---|---|---|---|---|---|---|"]
for r in dev:
    L.append(f"| {r['corner']} | {r['temp_C']} | {float(r['nmos_Id_0p9_uA']):.1f} | {float(r['pmos_Id_0p9_uA']):.3f} | {float(r['nmos_Id_1p8_uA']):.1f} | {float(r['pmos_Id_1p8_uA']):.1f} | {float(r['nmos_Vth_V']):.4f} | {float(r['pmos_Vth_V']):.4f} |")
L += ["", "## Textbook-ordering checks (results/corner_audit/factorial_summary.json)", ""]
L += [f"- {'PASS' if ok else 'FAIL'}: {k}" for k, ok in fa["checks"]]
L += ["", "## 3x3 factorial tables (rows NMOS slow/typ/fast; columns PMOS slow/typ/fast)", ""]
for name, d in fa["tables"].items():
    L += [f"**{name}**", "", "| | P slow | P typ | P fast |", "|---|---|---|---|"]
    for n, nn in zip("stf", ("N slow", "N typ", "N fast")):
        L.append(f"| {nn} | " + " | ".join(f"{d['n'+n+'p'+p]:.2f}" for p in "stf") + " |")
    L.append("")
(ROOT / "results/final_numbers.md").write_text("\n".join(L))
print("wrote results/final_numbers.md", len(L), "lines")
